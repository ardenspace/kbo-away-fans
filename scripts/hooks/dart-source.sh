#
# ─────────────────────────────────────────────────────────────────────────
# 왜 이 파일이 생겼는가.
# ─────────────────────────────────────────────────────────────────────────
#
# round 9 의 거부 사유 셋 중 둘이 같은 뿌리였다: **검사가 소스 텍스트만 보고
