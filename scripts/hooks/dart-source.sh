#     `lib/content/kst.dart` 에 블록 주석으로 감싼 `export` 줄을 두면 2-a) 가,
#     블록 주석 안의 줄이 문자로 시작하면(`gameDateOf 는 …`) 2-c) 가 각각
#     exit 2 였다.
#
# 직전 라운드가 **선언 머리를 읽는 규칙**을 훅 안에서 한 자리로 모은 것과 같은
# 종류의 문제다. 주석을 걷어 내는 규칙도 여기 한 번만 적고, 부르는 쪽은 전부
# 이 파일을 통한다. **같은 개념을 두 자리에 따로 적으면 어긋남이 다시 생긴다.**
#
# ─────────────────────────────────────────────────────────────────────────
# round 10 이 이 파일에서 고친 것.
# ─────────────────────────────────────────────────────────────────────────
#
# round 9 가 세운 첫 판의 훑는 규칙은 문자열을 **한 줄 안에서 여는 따옴표와
# 같은 다음 따옴표까지**로 읽었다. 그래서 문자열 보간(`${…}`) 안에 **같은
# 따옴표의 문자열이 중첩되면** 여는 문자열이 그 안쪽 따옴표에서 닫힌 것으로
# 읽혔고, 그 뒤에 오는 `//` 를 줄 주석으로 보아 **그 줄의 나머지를 잘라
# 냈다.** 검증자 재현:
#
#     원본: final v = '${a ?? 'https://a.b'}/x';
#     첫 판의 사본: final v = '${a ?? 'https:
#
# 이것은 **이 저장소가 실제로 쓰는 모양**이다:
# `lib/features/home/home_screen.dart:228`·`:403` 과
# `test/features/home/next_away_game_test.dart:252` 가 같은 중첩 보간이다(그
# 파일들에 `//` 가 없어 그때 잘리지 않았을 뿐이다). 검증자가 그 잘림으로
# `check-no-location-upload.sh` 의 검사 5)·4)(b) 가 실제 위반을 놓치는 것을
# 확인했다.
#
# 그래서 훑는 규칙을 **상태 더미(stack)** 로 다시 세웠다. 문자열 안의 `${` 는
# 코드 자리를 다시 열고(그 안에서 문자열·주석·중괄호를 다시 센다), 짝이 맞는
# `}` 에서 문자열로 돌아온다. 깊이 제한은 없다.
#
# ─────────────────────────────────────────────────────────────────────────
# 무엇을 하고 무엇은 하지 않는가 — **아래 목록은 전부 실측이다.**
# ─────────────────────────────────────────────────────────────────────────
#
# 하는 일: 파일을 한 번 훑으면서 줄 주석(`//`, `///`)과 블록 주석(`/* */`,
# 중첩까지)을 지우고 **줄 수와 줄 번호를 그대로 둔 사본**을 만든다. 그래서
# 부르는 쪽의 `grep -n`·`awk FNR` 이 원본과 같은 줄 번호를 낸다. 블록 주석은
# 지우는 대신 **공백 하나로 접는다** — 토막 사이의 주석이 두 토막을 붙여
# 버리면 부르는 쪽이 선언을 읽지 못하기 때문이다(`final/*c*/int x`).
#
# 하지 않는 일: **문자열 리터럴의 내용은 건드리지 않는다.** 검사 2) 가 import
# 의 URI 를 그 문자열에서 읽어야 하기 때문이다. 대신 문자열을 **알아보기는**
# 한다 — 그러지 않으면 `'https://…'` 의 `//` 나 `'/*'` 를 주석
# 표지로 잘못 읽는다.
#
# **바르게 다루는 것.** round 12 가 아래를 하나씩 `.dart` 파일로 지어 **먼저
# `dart analyze` 로 성립하는 Dart 인 것을 확인한 뒤**(52가지, 오류 0 — 경고는
# `??` 예제의 dead_code 둘뿐이다) 이 규칙에 먹였다. 52가지 전부 사본이 서고
# (exit 0), BSD awk 20200816 과 mawk 가 **바이트까지 같은** 사본을 냈으며, 두
# 사본의 줄 수와 각 줄의 글자 수가 같았다. 그 가운데 열여섯 가지는
# `test/features/badges/visit_check_test.dart` 의 `_mirrorCorpus` 에 픽스처로
# 남아 매 실행마다 다시 잰다.
#
# **이 목록을 늘리는 사람에게.** 늘린 줄을 `.dart` 파일로 지어 `dart analyze`
# 와 이 규칙에 함께 먹이고, 재지 않았으면 "아직 재지 않았다"라고 적으십시오.
# round 12 의 거부 사유 둘이 **이 목록 안에 재지 않은 문장이 섞여 있었던
# 것**이다(아래 "round 12 가 고친 것").
#
#   · 홑따옴표·겹따옴표 문자열, 그 각각의 세 겹(`'''`·`"""`, 줄을
#     넘긴다), raw 접두어(`r'…'`·`r"""…"""`, 역슬래시가 이스케이프가 아니다).
#   · 세 겹 안의 홀수 개 같은 따옴표 — `'''it's fine'''` 과
#     `"""he said "x" ok"""` **둘 다** (앞엣것이 round 11 의 거부 사유였는데
#     그때 픽스처가 뒤엣것을 담지 않았다).
#   · 문자열 안의 `//`·`/*`·`*/`·`print(` — 그대로 남는다.
#   · 이스케이프: `'it\'s'` · `"he said \"x\""` · `'a\\'`
#     (역슬래시로 끝나는 문자열) · **줄 끝의 역슬래시**(여러 줄 문자열 안에서
#     줄이 `\` 로 끝나는 것 — round 12 의 거부 사유가 이 자리다).
#   · **중첩 보간**: `'${a ?? 'https://a.b'}/x'` ·
#     `'a${'b${'c'}d'}e'` (깊이 제한 없음).
#   · 보간 안의 코드: 중괄호(`'${ {'k': 1}.length }'`),
#     닫는 중괄호를 담은 문자열(`'${f('}')}'`), 블록 주석
#     (`'${ /* } */ a}'`), raw 문자열(`'${r'x'}'`), 세 겹 문자열
#     (`'${"""x"""}'`), 그리고 **줄을 넘기는 보간** — 한 줄짜리 문자열에서도
#     보간 안에는 줄바꿈이 올 수 있다(실측: `dart analyze` 무지적).
#   · **보간 안의 줄 주석** — 보간 안은 코드 자리라 줄 주석이 성립한다. 세 겹
#     이든 한 줄짜리든 같고, 그 줄의 나머지만 버린 뒤 다음 줄에서 같은 보간을
#     이어 읽는다. (같은 줄에서 닫으려는 입력만 성립하지 않는데, 그것은
#     아래 2)로 나온다.)
#   · 이스케이프한 보간 표지: `'\${notInterp}//still string'` 는
#     통째로 문자열이다.
#   · **중괄호 없는 보간**(`'$name'`)은 알아보지 않고 **문자열 내용으로**
#     지나간다. 안전한 것은 이름 하나에 따옴표도 중괄호도 주석 표지도 들어갈
#     수 없기 때문이고, blank 사본은 그 자리까지 통째로 지운다(실측).
#   · raw 문자열 안의 `${…}` 는 보간이 아니다 (Dart 가 그렇다).
#   · 주석 세 갈래(`//`·`///`·`/* */`)와 **줄을 넘기는** 블록 주석, 그 중첩
#     (`/* /* x */ */`), 코드 사이 접힘(`final/*c*/int x` → `final int x`),
#     주석 안의 문자열 표지(`// 주석 안의 '따옴표` · `/* ' 와 " */`).
#   · 나란한 문자열(`'a' 'b'`)과 사이에 주석이 낀 것(`'a' /* c */ 'b'`),
#     빈 문자열(`''`), 빈 세 겹(`''''''`), 세 겹 안의 홑따옴표(`'''a'b'''`),
#     세 겹 안의 다른 세 겹(`"""a ''' b"""`).
#   · 나눗셈과 주석이 붙은 자리(`x = a / /* c */ b;`), 제네릭·맵 리터럴
#     (`<String, int>{'a': 1}`), 이름으로 쓴 `r`(`final r = 'x';` — raw
#     접두어로 읽지 않는다).
#
# **다루지 못하는 것 — 그리고 그것이 어떻게 드러나는가.** 조용히 자르는 갈래는
# 없다. 둘 다 stderr 에 적고 exit 1 이며, `dart_source_mirror` 가 그것을 받아
# exit 2 로 세운다(검사가 그 사본을 보고 통과하는 일이 없다).
#
#   1. **닫히지 않은 블록 주석으로 파일이 끝났다** → "닫히지 않은 블록 주석으로
#      파일이 끝났습니다".
#   2. **닫히지 않은 문자열로 파일이 끝났다** → "닫히지 않은 문자열로 파일이
#      끝났습니다". 한 줄짜리 문자열이 그 줄에서 닫히지 않으면 뒤의 줄들을
#      계속 문자열로 읽다가 여기서 걸린다(첫 판은 그 줄 끝에서 조용히
#      털어 버렸다). **같은 줄에서 닫으려는 보간 안의 줄 주석**
#      (`final v = '${a // c}';`)도 이 갈래로 나온다 — 그 줄 주석이 닫는
#      따옴표까지 먹어서 문자열이 끝내 닫히지 않기 때문이다.
#
#   둘 다 `dart analyze` 가 함께 빨간불이다 — round 12 가 각각 `.dart` 파일로
#   지어 확인했다. 1(`/* x`)은 "Unterminated multi-line comment",
#   2(`final a = 'x;`)는 "Expected to find ';'" 와 "Unterminated string
#   literal", 2 의 짝인 같은 줄 보간 주석(`final v = '${a // c}';`)은
#   "Unterminated string literal" 을 비롯한 오류 넷이다. 그리고 둘 다
#   **파일 이름과 함께** 적힌다(awk 자신의 종료 상태가 1 인 것도 실측했다).
#   둘이 **각자의 까닭을** 적는 것과 `dart_source_mirror` 가 그것을 2 로
#   세우는 것은 시험이 잰다
#   (`test/features/badges/visit_check_test.dart` 의 "사본을 만들지 못하는
#   입력은 조용히 통과하는 대신 2 로 선다"). round 11 까지는 그것을 재는
#   시험이 없어서, 실패 표면화 장치를 아무 일도 하지 않게 만들거나
#   `dart_source_mirror` 가 awk 실패를 삼키게 만들어도 전부 초록불이었다.
#
#   **위 목록 밖의 Dart 문법은 "찾지 못했다"라고만 적는다 — 닫힌 목록이
#   아니다.** round 12 가 52가지를 지어 먹였고 그중 오탐은 없었지만, 그것은
#   53번째가 없다는 뜻이 아니다. 직전 판은 같은 자리에 "실측으로 찾지
#   못했다"라고 적어 두었는데 그 목록 안에 이미 오탐이 하나 앉아 있었고, 그
#   문장이 다음 사람이 그것을 고칠 생각을 하지 못하게 막고 있었다. 이것은
#   Dart 파서가 아니라 문자 훑기라서, 목록 밖의 성립하지 않는 입력이 들어오면
#   사본이 어긋날 수 있다. 그때 어긋남은 위 둘 중 하나로 나오거나
#   (따옴표·중괄호의 짝이 깨지면 파일 끝까지 먹는다), 사본이 원본보다 **덜**
#   지워진 모양으로 나온다 — 검사가 못 보는 쪽이 아니라 더 보는 쪽이다.
#
# 알아보는 문자열은 넷이다: 홑따옴표·겹따옴표, 그 각각의 세 겹
# (`'''`·`"""`, 줄을 넘긴다), 그리고 raw 접두어(`r'…'`).
#
# ─────────────────────────────────────────────────────────────────────────
# round 11 이 이 파일에서 고친 것 — 사본이 **둘**이 되었다.
# ─────────────────────────────────────────────────────────────────────────
#
# round 11 의 거부 사유는 **문자열을 알아보는 규칙이 이 저장소에 두 자리
# 있었다는 것**이다. 여기 헤더는 위 넷을 알아본다고 적었고 실제로 그랬는데,
# `check-no-location-upload.sh` 의 검사 4) 가 문장을 끊으려고 **자기 훑기에
# 다시 적은** 규칙은 홑따옴표·겹따옴표 둘만 알았다. 그래서 세 겹 문자열 안의
# 홀수 개 홑따옴표 하나(`'''it's fine'''` — Dart 가 이스케이프를 요구하지 않는
# 가장 평범한 표기이고, 이 저장소도 이미 쓴다)에 그 훑기가 파일 끝까지 눈이
# 멀었다. 얼굴이 둘이었다: 파일이 클래스 몸통으로 끝나면 삼켜진 구간의 최상위
# 저장소가 **조용히 통과**했고(검증자 재현: `DeviceFix? lastSpot;` 이 훅 4종·
# analyze·시험 684개를 전부 지났다), 그렇지 않으면 정당한 코드가 **원인과
# 무관한 자리를 가리키는 오탐**으로 걸렸다. 보간 안의 문자열에 담긴 닫는
# 중괄호(`'${f('}')}'`)도 같은 뿌리로 어긋났다.
#
# 이 저장소가 같은 뿌리로 거부당한 것이 세 번째였다(round 8 선언 머리 읽기,
# round 9 주석 걷어내기, round 11 문자열 알아보기). 앞의 둘과 같은 방식으로
# 푼다: **문자열을 알아보는 상태 기계를 이 파일 하나에만 둔다.**
#
# 부르는 쪽이 문자열을 다시 파싱하지 않아도 되도록, 한 번 훑으면서 사본을
# **둘** 낸다.
#
#   · **code 사본** — 주석만 걷어 내고 문자열 내용은 그대로. 문자열의 *내용*이
#     필요한 쪽이 읽는다(검사 2) 가 import 의 URI 를 거기서 읽는다).
#   · **blank 사본** — 그 위에서 문자열 리터럴을 통째로 공백으로 지운 것.
#     여는·닫는 따옴표도, `r` 접두어도, **보간(`${…}`) 안의 코드까지** 지운다.
#     그래서 이 사본에는 따옴표가 한 글자도 남지 않고, 남은 `;`·`{`·`}` 는
#     전부 코드다. 문자열이 *어디까지인지*만 필요한 쪽이 읽는다(검사 4)).
#
# 두 사본은 **줄 수도 각 줄의 글자 수도 같다** — blank 사본은 지운 자리에
# 같은 길이의 공백을 넣고 줄바꿈은 그대로 둔다. 그래서 부르는 쪽의 줄 번호가
# 원본과 어긋나지 않는다. **round 12 까지 이 문장은 거짓이었다**(아래 "round
# 12 가 고친 것"). 이제 시험이 그것을 **줄마다 바이트로** 잰다
# (`visit_check_test.dart` 의 "셸 판의 두 사본은 줄 수도 각 줄의 글자 수도
# 같다" — 픽스처 열여섯 가지의 모든 줄).
#
# **원본과 견주면 다른 것이 하나 있다.** 마지막 줄바꿈이 없는 파일에 awk 의
# `print` 가 줄바꿈을 하나 더한다(실측: 12바이트 원본 → 13바이트 사본). 줄
# 번호는 그대로라 부르는 쪽에 닿지 않고, 이 저장소의 `lib`·`test` 의 dart
# 파일 150개는 전부 줄바꿈으로 끝난다(실측). 어긋남 자체와 그 전제를 시험이
# 함께 못 박는다(`visit_check_test.dart` 의 "마지막 줄바꿈이 없는 파일에서 두
# 판이 갈리는 자리는 여기 못 박는다").
#
# blank 사본을 읽는 쪽은 **따옴표가 남아 있으면 멈춘다** — 그 전제가 깨졌다는
# 뜻이고, 그것이 조용히 통과하는 것이 round 11 의 거부 사유였기 때문이다.
#
# (같은 유형의 구분이지만 **합치지 않은** 자리도 하나 적어 둔다:
# `check-no-location-upload.sh` 의 `DECL_MODIFIERS`(선언 머리의 class
# modifier)와 필드 수식어 집합은 이름이 겹치지만 다른 개념이고, 왜 같아서는
# 안 되는지가 그 자리에 적혀 있다.)
#
# ─────────────────────────────────────────────────────────────────────────
# round 12 가 이 파일에서 고친 것 — **헤더의 문장 둘이 거짓이었다.**
# ─────────────────────────────────────────────────────────────────────────
#
# round 12 의 거부 사유는 계약 위반이 아니라 **이 헤더**였다. 위 목록이
# "전부 실측이다"라고 선언한 자리에 재지 않은 문장이 둘 섞여 있었고, 그중
# 하나가 오탐을 낳고 있었다.
#
# **(1) 보간 안의 줄 주석을 "성립하지 않는 입력"이라 적고 막았다 — 오탐.**
# 옛 판에는 갈래가 셋이었고 셋째가 `bail()` 이었다: 가장 안쪽 문자열이 세 겹이
# 아닌 채로 보간 안에서 `//` 를 만나면 exit 1. 헤더는 그것을 "Dart 로도
# 성립하지 않는 입력"·"애초에 성립하지 않는 입력"이라고 적었는데 거짓이다 —
# **보간이 줄을 넘기면 줄 주석이 닫는 따옴표를 먹지 않는다.** 지휘자 재현:
#
#     String debugLabel(String id) {
#       return '경기 ${id // 식별자는 schedule 계약이 준다
#           } 의 라벨';
#     }
#
# `flutter analyze` 의 지적은 lint 정보 하나뿐이고(`unnecessary_brace_in_
# string_interps`) 오류가 아닌데 `pre-commit` 이 exit 1 이었다. 선 것은
# `check-firebase-import-boundary.sh` 이고(exit 2), 그 훅이 `lib/` 전체를
# 사본으로 옮기므로 **판정 계층 밖의 아무 파일에서나** 섰다. 짝 훅
# `check-no-location-upload.sh` 는 `lib/location` 과 `lib/content/kst.dart`
# 만 옮겨서 같은 자리에서 exit 0 이었다(실측). 둘 다 CI 의 `conventions`
# job 에 걸려 있으므로 로컬 커밋과 CI 를 함께 막았다.
#
# 고친 값은 쌌다: `bail()` 을 없애고 세 겹과 같이 **그 줄의 나머지만 버린다.**
# 정말로 성립하지 않는 같은 줄 입력(`final v = '${a // c}';`)은 문자열이 끝내
# 닫히지 않으므로 END 의 2)가 그대로 받는다(실측: exit 2, "닫히지 않은
# 문자열로 파일이 끝났습니다"). 잃는 것이 없는데도 **헤더가 그 자리를
# "성립하지 않는 입력"이라고 적어 두어 다음 사람이 고칠 생각을 하지 못하게
# 막고 있었다.** 그것이 이 헤더를 이번에 한 문장씩 다시 잰 까닭이다.
#
# **(2) "두 사본은 줄 수도 각 줄의 글자 수도 같다"가 거짓이었다.** 여러 줄
# 문자열 안에서 줄이 역슬래시로 끝나면, 이스케이프를 무조건 두 글자로 세어
# blank 사본에 공백 두 칸을 넣었다. 그 줄에서 역슬래시는 **한 글자**다(줄바꿈은
# 다음 레코드다). 지휘자 재현 — 아래 3행에서 원본 8, code 8, blank **9**:
#
#     class Probe {
#       static const banner = '''
#       +---+\
#       | o |
#       +---+''';
#     }
#
# Dart 판(`_stripped`)은 역슬래시와 줄바꿈을 한 덩어리로 감춰 글자 수를 지키고
# 있었으므로 **두 판이 실제로 갈렸는데**, 두 판을 견주는 시험이 공백 런을
# 하나로 접어 보아서 그 어긋남을 못 봤다 — 접으면 공백 한 칸과 두 칸이 같은
# 한 칸이 된다(실측).
# `_mirrorCorpus` 의 `escapes` 항목이 "역슬래시로 끝나는 문자열"은 담는데
# **줄 끝의 역슬래시**는 담지 않아 픽스처도 짚지 못한 축이었다.
#
# 셋을 함께 고쳤다: 셸 판이 **실제로 집은 만큼만** 지우고, 동치 시험이 공백을
# 접는 대신 **바이트로 옮겨 글자 자리까지** 견주며(`_asShellBlank`),
# `_mirrorCorpus` 에 줄 끝 역슬래시 축이 들어갔다. 그리고 셸 판의 두 사본이
# 줄마다 같은 바이트 수인지를 재는 시험이 따로 섰다.
#
# **round 12 가 함께 찾은, 픽스처가 짚지 못하던 다른 축 넷**(전부 성립하는
# Dart 이고 전부 바르게 다뤄지고 있었다 — 재는 자리만 없었다): 세 겹 겹따옴표
# 안의 홀수 개 겹따옴표(round 11 은 홑따옴표 쪽만 담았다), `///` 와 줄을
# 넘기는 블록 주석(앞선 픽스처의 블록 주석은 전부 한 줄에서 닫혔다), 문자열
# 안의 `*/` 와 `print(`(헤더가 이름을 부른 넷 중 둘이 픽스처에 없었다),
# 중괄호 없는 보간(`'$name'`).
#
# ─────────────────────────────────────────────────────────────────────────
# 쓰는 법.
# ─────────────────────────────────────────────────────────────────────────
#
#   hook_dir=$(cd "$(dirname "$0")" && pwd)
#   . "$hook_dir/dart-source.sh"
#   MIRROR=$(mktemp -d) || exit 1
#   trap 'rm -rf "$MIRROR"' EXIT
#   dart_source_mirror "$MIRROR" lib || fail=2
#
# 그 뒤로는 `$MIRROR/code/<원본과 같은 상대 경로>` (주석만 걷어 낸 사본) 나
# `$MIRROR/blank/<같은 상대 경로>` (문자열까지 지운 사본) 를 읽는다.
# `grep -rn` 을 쓸 때는 `(cd "$MIRROR/code" && grep -rn … lib)` 로 부르면
# 출력의 경로가 원본과 같은 모양으로 나온다.
#
# **둘 중 어느 것을 읽을 것인가.** 문자열의 **내용**이 필요하면 code 사본이고
# (검사 2) 가 import 의 URI 를 거기서 읽는다), 문자열이 **어디까지인지**만
# 필요하면 blank 사본이다 (검사 4) 는 `;`·`{`·`}` 가 문자열 안인지만 가린다).
# blank 사본을 읽는 쪽은 문자열을 다시 파싱하지 않는다 — 그것이 이 파일이
# 있는 까닭이다.

DART_SOURCE_AWK='
  # 상태 더미. kind[k] 는 "B"(블록 주석) · "S"(문자열) · "I"(보간 안의 코드).
  # 더미가 비면 파일 최상위의 코드 자리다.
  BEGIN { top = 0; printf "" > (BLANK) }

  function push(k) { top++; kind[top] = k; quote[top] = ""; raw[top] = 0; brace[top] = 0 }

  function sp(n,   s) { s = ""; while (n-- > 0) s = s " "; return s }

  # 한 번 훑으면서 사본 **둘**을 함께 적는다.
  #   a → code 사본  : 주석만 걷어 내고 문자열 내용은 그대로 둔다.
  #   b → blank 사본 : 그 위에서 문자열 리터럴을 통째로 공백으로 지운다.
  # 부르는 쪽이 문자열을 다시 파싱하지 않도록, 문자열을 알아보는 일은 여기서
  # 끝낸다.
  function put(a, b) { out = out a; bout = bout b }

  {
    line = $0
    len = length(line)
    out = ""
    bout = ""
    i = 1
    while (i <= len) {
      state = (top > 0) ? kind[top] : "C"

      if (state == "B") {                         # 블록 주석 안 (중첩을 센다)
        two = substr(line, i, 2)
        if (two == "*/") { top--; i += 2; continue }
        if (two == "/*") { push("B"); i += 2; continue }
        i++
        continue
      }

      if (state == "S") {                         # 문자열 안 — code 사본은 내용을 그대로 두고 blank 사본은 지운다
        c = substr(line, i, 1)
        # 이스케이프는 **원본에서 실제로 집은 만큼만** 지운다. 줄 끝의
        # 역슬래시는 그 줄에서 한 글자뿐이므로(다음 줄은 다음 레코드다)
        # `substr` 이 한 글자를 준다 — 여기서 "  " 두 칸을 넣으면 blank 사본이
        # code 사본보다 한 글자 길어진다(round 12 의 거부 사유).
        if (!raw[top] && c == "\\") { esc = substr(line, i, 2); put(esc, sp(length(esc))); i += 2; continue }
        q = quote[top]
        if (substr(line, i, length(q)) == q) {
          put(q, sp(length(q))); i += length(q); top--
          continue
        }
        if (!raw[top] && c == "$" && substr(line, i + 1, 1) == "{") {
          put("${", "  "); i += 2; push("I"); brace[top] = 1
          continue
        }
        put(c, " "); i++
        continue
      }

      # 여기부터는 코드 자리다 — 파일 최상위("C") 이거나 보간 안("I").
      # **보간 안은 문자열 리터럴의 일부다** — blank 사본에서는 거기 있는
      # 중괄호·따옴표도 함께 지워야 부르는 쪽이 그것을 코드로 읽지 않는다
      # (`${f("}")}` 의 닫는 중괄호가 그 자리다).
      inStr = (state == "I")
      two = substr(line, i, 2)
      # 줄 주석 — 이 줄의 나머지를 버리고 상태는 그대로 다음 줄로 넘긴다.
      # 보간(`${…}`) 안에서 만나도 같다: 보간 안은 코드 자리라 줄 주석이
      # 성립하고, 그 보간이 다음 줄에서 이어진다.
      if (two == "//") { break }
      # 블록 주석은 **공백 하나로** 접는다 — 토막 사이에 있던 주석이 두 토막을
      # 붙여 버리지 않도록 (`final/*c*/int x` 가 `finalint x` 가 되면 부르는
      # 쪽이 선언을 읽지 못한다).
      if (two == "/*") { push("B"); i += 2; put(" ", " "); continue }

      c = substr(line, i, 1)
      if (state == "I") {                         # 보간의 짝을 센다
        if (c == "{") { brace[top]++; put(c, " "); i++; continue }
        if (c == "}") {
          if (brace[top] <= 1) { top--; put(c, " "); i++; continue }
          brace[top]--; put(c, " "); i++
          continue
        }
      }

      isRaw = 0
      if (c == "r" && (substr(line, i + 1, 1) == "\047" || substr(line, i + 1, 1) == "\"") \
          && (i == 1 || substr(line, i - 1, 1) !~ /[A-Za-z0-9_$]/)) {
        put(c, " "); i++                          # raw 접두어도 리터럴의 일부다
        c = substr(line, i, 1)
        isRaw = 1
      }
      if (c == "\047" || c == "\"") {
        q3 = c c c
        if (substr(line, i, 3) == q3) {           # 세 겹 — 줄을 넘길 수 있다
          push("S"); quote[top] = q3; raw[top] = isRaw
          put(q3, "   "); i += 3
          continue
        }
        push("S"); quote[top] = c; raw[top] = isRaw
        put(c, " "); i++
        continue
      }
      put(c, inStr ? " " : c); i++
    }
    print out
    print bout > (BLANK)
  }

  END {
    if (top > 0) {
      for (k = top; k >= 1; k--) {
        if (kind[k] == "B") { why = "닫히지 않은 블록 주석으로 파일이 끝났습니다"; break }
        if (kind[k] == "S") { why = "닫히지 않은 문자열로 파일이 끝났습니다"; break }
      }
      if (why == "") why = "닫히지 않은 문자열 보간으로 파일이 끝났습니다"
      printf "%s: %s\n", FILENAME, why > "/dev/stderr"
      exit 1
    }
  }
'

# 주어진 자리들 아래의 `*.dart` 를 사본 **둘**로 $1 아래에 만든다.
#
#   $1/code/<원본과 같은 상대 경로>   주석만 걷어 낸 사본
#   $1/blank/<원본과 같은 상대 경로>  그 위에서 문자열 리터럴까지 지운 사본
#
# 상대 경로는 원본 그대로 둔다 — 부르는 쪽이 원본 경로로 메시지를 낼 수 있다.
#
# awk 가 실패하거나 사본이 하나도 생기지 않으면 **조용히 통과하는 대신**
# stderr 에 적고 2 를 돌려준다. 그 침묵이 이 저장소가 round 6·7 에서 두 번
# 고친 모양이다.
dart_source_mirror() {
  local mirror=$1
  shift
  local rc=0 count=0 root f out blank
  for root in "$@"; do
    if [ ! -e "$root" ]; then
      echo "dart_source_mirror: $root 이 없습니다." >&2
      rc=2
      continue
    fi
    while IFS= read -r f; do
      out="$mirror/code/$f"
      blank="$mirror/blank/$f"
      if ! mkdir -p "$(dirname "$out")" || ! mkdir -p "$(dirname "$blank")"; then
        echo "dart_source_mirror: $out 의 자리를 만들지 못했습니다." >&2
        rc=2
        continue
      fi
      if awk -v BLANK="$blank" "$DART_SOURCE_AWK" "$f" > "$out"; then
        count=$((count + 1))
      else
        echo "dart_source_mirror: $f 에서 주석을 걷어 내지 못했습니다 — 검사가 조용히 통과하는 대신 여기서 멈춥니다." >&2
        rc=2
      fi
    done < <(find "$root" -type f -name '*.dart' | sort)
  done
  if [ "$count" -eq 0 ]; then
    echo "dart_source_mirror: 사본이 하나도 생기지 않았습니다 ($*) — 아래 검사들이 이 사본을 보고 있으므로 여기서 멈춥니다." >&2
    rc=2
  fi
  return $rc
}
